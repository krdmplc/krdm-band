#!/usr/bin/env node
// One-time import of the website's merch (krdm-www/content/merch/*.md) into the app.
// Writes build/import.sql (products, owners, prices, sizes, photos, known stock) and
// build/import-images.sh (copies the photos into R2). Safe to run twice: rows that
// already exist are left alone.
//
//   node scripts/import-hugo.mjs ../krdm-www
//   npx wrangler d1 execute krdm-merch --local --file build/import.sql
//   sh build/import-images.sh --local          (or --remote, for both)
//
// Mapping:
// - owner: the item's one listed band; none or several (the KRDM shirt) → the label "krdm";
// - sizes and photos come from the Slovenian file (the website keeps them only there);
// - `stock` per size and `quantity` become stock at the location "Zaloga (uvoz)",
//   which is sold online. Sizes without a count get no stock: count them in the app;
// - draft items are imported unpublished; weights are a guess by kind, check them.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import matter from 'gray-matter'

const site = resolve(process.argv[2] ?? '../krdm-www')
const merchDir = join(site, 'content/merch')
if (!existsSync(merchDir)) {
  console.error(`No ${merchDir}. Usage: node scripts/import-hugo.mjs <path to krdm-www>`)
  process.exit(1)
}

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const read = (file) => matter(readFileSync(file, 'utf8'))

function guessWeight (id, category) {
  if (/hoodie|pulover|jopa/.test(id)) return 700
  if (/cap|kapa|hat/.test(id)) return 120
  if (category === 'apparel') return 200
  if (/vinyl|vinil|lp/.test(id)) return 450
  if (/cassette|kaseta/.test(id)) return 80
  if (/minidisc/.test(id)) return 60
  if (/cd/.test(id)) return 120
  return 100
}

const contentType = (file) => (/\.png$/i.test(file) ? 'image/png' : /\.webp$/i.test(file) ? 'image/webp' : 'image/jpeg')

function imageSize (file) {
  try {
    const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' })
    const w = Number(/pixelWidth: (\d+)/.exec(out)?.[1])
    const h = Number(/pixelHeight: (\d+)/.exec(out)?.[1])
    return w && h ? [w, h] : [null, null]
  } catch {
    return [null, null] // not on macOS: the website reads sizes itself
  }
}

const sql = [
  '-- Generated by scripts/import-hugo.mjs',
  "INSERT OR IGNORE INTO owners (id, name, kind) VALUES ('krdm', 'KRDM', 'label');",
  "INSERT OR IGNORE INTO locations (id, name, online) VALUES ('import', 'Zaloga (uvoz)', 1);"
]
const images = []
const owners = new Set()
const report = { products: 0, photos: 0, pieces: 0, uncounted: [] }

const files = readdirSync(merchDir).filter((f) => f.endsWith('.sl.md') && !f.startsWith('_index'))
for (const file of files) {
  const id = file.replace(/\.sl\.md$/, '')
  const sl = read(join(merchDir, file))
  const enFile = join(merchDir, `${id}.en.md`)
  const en = existsSync(enFile) ? read(enFile) : { data: {}, content: '' }
  const d = sl.data
  const artists = d.artists ?? []
  const owner = artists.length === 1 ? artists[0] : 'krdm'
  if (owner !== 'krdm' && !owners.has(owner)) {
    owners.add(owner)
    const artistFile = join(site, 'content/artists', owner, '_index.sl.md')
    const name = existsSync(artistFile) ? read(artistFile).data.title ?? owner : owner
    sql.push(`INSERT OR IGNORE INTO owners (id, name, kind) VALUES (${q(owner)}, ${q(name)}, 'band');`)
  }
  const category = ['apparel', 'music', 'other'].includes(d.category) ? d.category : 'other'
  sql.push(`INSERT OR IGNORE INTO products (id, owner_id, title_sl, title_en, description_sl, description_en, category, link, release, weight_g, published) VALUES (${[
    q(id), q(owner), q(d.title ?? id), q(en.data.title ?? ''), q(sl.content.trim()), q(en.content.trim()), q(category),
    q(d.link ?? null), q(d.release ?? null), guessWeight(id, category), d.draft ? 0 : 1
  ].join(', ')});`)
  if (typeof d.price === 'number') {
    sql.push(`INSERT OR IGNORE INTO product_prices (product_id, tier_id, price_cents) VALUES (${q(id)}, 'full', ${Math.round(d.price * 100)});`)
  }
  const sizes = Array.isArray(d.sizes) && d.sizes.length ? d.sizes : [{ size: '', stock: d.quantity }]
  sizes.forEach((s, i) => {
    const size = String(s.size ?? '')
    sql.push(`INSERT OR IGNORE INTO product_sizes (product_id, size, sort) VALUES (${q(id)}, ${q(size)}, ${i});`)
    if (typeof s.stock === 'number' && s.stock > 0) {
      sql.push(`INSERT OR IGNORE INTO stock_entries (id, product_id, size, location_id, qty, type, note) VALUES (${q(`import-${id}-${size}`)}, ${q(id)}, ${q(size)}, 'import', ${s.stock}, 'received', 'uvoz s spletne strani');`)
      report.pieces += s.stock
    } else if (d.available !== false && !d.draft) {
      report.uncounted.push(`${id}${size ? ` ${size}` : ''}`)
    }
  })
  const photos = [d.thumbnail, ...(d.images ?? [])].filter(Boolean)
  photos.forEach((path, i) => {
    const local = join(site, 'static', path)
    if (!existsSync(local)) return
    const key = `imported/${basename(path)}`
    const [w, h] = imageSize(local)
    sql.push(`INSERT OR IGNORE INTO product_images (id, product_id, key, width, height, bytes, sort) VALUES (${q(`import-${id}-${i}`)}, ${q(id)}, ${q(key)}, ${q(w)}, ${q(h)}, ${statSync(local).size}, ${i});`)
    images.push({ key, local })
    report.photos++
  })
  report.products++
}

mkdirSync('build', { recursive: true })
writeFileSync('build/import.sql', sql.join('\n') + '\n')
writeFileSync('build/import-images.sh', [
  '#!/bin/sh',
  '# Copies the imported photos into R2. Pass --local or --remote.',
  'set -e',
  ...images.map(({ key, local }) => `npx wrangler r2 object put ${q(`krdm-merch-images/${key}`)} --file ${q(local)} --content-type ${contentType(local)} "$1"`)
].join('\n') + '\n')

console.log(`Products: ${report.products}, photos: ${report.photos}, pieces of stock: ${report.pieces}`)
console.log('Wrote build/import.sql and build/import-images.sh')
if (report.uncounted.length) {
  console.log(`\nNo count on the website (count these in the app, Stock → Count):\n  ${report.uncounted.join('\n  ')}`)
}
